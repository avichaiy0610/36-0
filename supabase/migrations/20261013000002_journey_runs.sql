-- מסע ה־11 (v1.61): one row per finished route, the six route achievements as
-- real ones, the public records board (journey_board), and the admin list of
-- who played. 'journey' in track() is
-- 20261013000001.
--
-- The mode runs in the browser, so what reaches the server is checked, never
-- trusted as given. Every squad must be one the game has (journey_squads below,
-- generated from js/data.js by scripts/build_journey_squads_sql.js). The server
-- holds no players, so it cannot replay a career link; what it CAN derive from
-- the route itself, it derives: the club and the season are the squad id
-- (`<club>-<start year>`), so the club limit, the year gap (jx_time) and the
-- moves back in time (jx_back) are computed here, not read from the client.
-- `broken` and `rank` are trust-on-submit, like the other client-run modes.
-- Keys, names and icons are kept equal to js/journey-achievements.js by
-- scripts/sim/journey_server_test.js, and so is the squad list.
--
-- A route is sent when the eleventh man is taken (rank null), again after its
-- season (rank 1-16), and again from the device's queue after a sign-in. Only
-- the FIRST call writes the route; every later one may add a missing rank and
-- nothing else, and the awards are always computed from the stored row — a
-- repeat with another route, level or rank cannot earn what the row does not
-- (Codex's review of 7e852605).
--
-- array_append, never `earned || 'key'` (20260831000001: an untyped literal on
-- the right parses as an array and aborts the whole function).

CREATE TABLE IF NOT EXISTS journey_runs (
  id          bigserial PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  run_id      text NOT NULL,
  level       text NOT NULL,
  formation   text NOT NULL DEFAULT '',
  route       jsonb NOT NULL,
  broken      boolean NOT NULL,
  clubs       int  NOT NULL,
  year_gap    int  NOT NULL,
  backwards   int  NOT NULL,
  ovr         int,
  rank        int,
  -- the season, written together with rank and never after it
  wins        int,
  draws       int,
  losses      int,
  gf          int,
  ga          int,
  points      int,
  created_at  timestamptz NOT NULL DEFAULT now(),
  season_at   timestamptz,
  UNIQUE (user_id, run_id)
);
CREATE INDEX IF NOT EXISTS journey_runs_created_idx ON journey_runs (created_at DESC);
CREATE INDEX IF NOT EXISTS journey_runs_board_idx ON journey_runs (level, points DESC) WHERE points IS NOT NULL;
ALTER TABLE journey_runs ENABLE ROW LEVEL SECURITY;
-- no policies: rows are written by submit_journey_run only

