CREATE OR REPLACE FUNCTION submit_journey_run(p jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  uid        uuid   := auth.uid();
  v_run      text   := COALESCE(p->>'run_id', '');
  v_level    text   := COALESCE(p->>'level', '');
  v_form     text   := LEFT(COALESCE(p->>'formation', ''), 12);
  v_route    jsonb  := p->'route';
  v_broken   boolean;
  v_rank     int;
  v_ovr      int;
  v_el       jsonb;
  v_i        int;
  v_id       text;
  v_clubs    text[] := '{}';
  v_years    int[]  := '{}';
  v_names    text[] := '{}';
  v_ids      text[] := '{}';
  v_clean    jsonb  := '[]'::jsonb;
  v_nclubs   int;
  v_maxper   int;
  v_gap      int;
  v_back     int    := 0;
  v_row      journey_runs%ROWTYPE;
  v_season   jsonb  := p->'season';
  v_w        int;
  v_d        int;
  v_l        int;
  v_gf       int;
  v_ga       int;
  earned     text[] := '{}';
  fresh      text[] := '{}';
BEGIN
  IF uid IS NULL THEN RETURN jsonb_build_object('error', 'not signed in'); END IF;
  IF v_run !~ '^[a-z0-9-]{4,40}$' OR v_level NOT IN ('easy','normal','hard','legacy') THEN
    RETURN jsonb_build_object('error', 'bad run');
  END IF;

  -- exactly eleven stations of {squadId, name}
  IF jsonb_typeof(v_route) IS DISTINCT FROM 'array' OR jsonb_array_length(v_route) <> 11 THEN
    RETURN jsonb_build_object('error', 'bad route');
  END IF;
  FOR v_i IN 0..10 LOOP
    v_el := v_route->v_i;
    IF jsonb_typeof(v_el) IS DISTINCT FROM 'object'
       OR jsonb_typeof(v_el->'squadId') IS DISTINCT FROM 'string'
       OR jsonb_typeof(v_el->'name') IS DISTINCT FROM 'string'
       OR (v_el->>'squadId') !~ '^[a-z0-9]+(-[a-z0-9]+)*-(199[0-9]|20[0-4][0-9])$'
       OR length(v_el->>'name') NOT BETWEEN 1 AND 60 THEN
      RETURN jsonb_build_object('error', 'bad route');
    END IF;
    v_id    := v_el->>'squadId';
    v_ids   := array_append(v_ids, v_id);
    v_names := array_append(v_names, v_el->>'name');
    v_clubs := array_append(v_clubs, regexp_replace(v_id, '-[0-9]{4}$', ''));
    v_years := array_append(v_years, right(v_id, 4)::int);
    v_clean := v_clean || jsonb_build_array(jsonb_build_object('squadId', v_id, 'name', v_el->>'name'));
    IF v_i > 0 AND v_years[v_i + 1] < v_years[v_i] THEN v_back := v_back + 1; END IF;
  END LOOP;

  -- no squad and no player twice, and every squad one the game has
  IF (SELECT count(DISTINCT x) FROM unnest(v_ids) x) <> 11
     OR (SELECT count(DISTINCT x) FROM unnest(v_names) x) <> 11
     OR (SELECT count(*) FROM journey_squads WHERE id = ANY (v_ids)) <> 11 THEN
    RETURN jsonb_build_object('error', 'bad route');
  END IF;

  -- the level's club limit: once on רגיל/קשה, twice on קל, none on a pre-level route
  SELECT count(DISTINCT c), max(n) INTO v_nclubs, v_maxper
    FROM (SELECT c, count(*) AS n FROM unnest(v_clubs) c GROUP BY c) t;
  IF (v_level IN ('normal','hard') AND v_maxper > 1) OR (v_level = 'easy' AND v_maxper > 2) THEN
    RETURN jsonb_build_object('error', 'bad route');
  END IF;
  SELECT max(y) - min(y) INTO v_gap FROM unnest(v_years) y;

  v_broken := COALESCE(p->'broken' = 'true'::jsonb, false);
  IF jsonb_typeof(p->'rank') = 'number' AND (p->>'rank')::numeric BETWEEN 1 AND 20
     AND (p->>'rank')::numeric = trunc((p->>'rank')::numeric) THEN
    v_rank := (p->>'rank')::numeric::int;
  END IF;
  -- A rank comes with its season or not at all. Read raw, judged, never clamped:
  -- clamping once turned a 40-win claim into a "perfect" 36-0 on the salary board
  -- (20260901000002). The points are the server's, 3W+D, not the client's.
  IF v_rank IS NOT NULL THEN
    IF jsonb_typeof(v_season) IS DISTINCT FROM 'object'
       OR EXISTS (SELECT 1 FROM unnest(ARRAY['wins','draws','losses','gf','ga']) k
                  WHERE jsonb_typeof(v_season->k) IS DISTINCT FROM 'number'
                     OR (v_season->>k)::numeric <> trunc((v_season->>k)::numeric)
                     OR (v_season->>k)::numeric < 0
                     OR (v_season->>k)::numeric > 300) THEN
      RETURN jsonb_build_object('error', 'bad season');
    END IF;
    v_w  := (v_season->>'wins')::numeric::int;
    v_d  := (v_season->>'draws')::numeric::int;
    v_l  := (v_season->>'losses')::numeric::int;
    v_gf := (v_season->>'gf')::numeric::int;
    v_ga := (v_season->>'ga')::numeric::int;
    IF v_w + v_d + v_l NOT BETWEEN 1 AND 36 THEN
      RETURN jsonb_build_object('error', 'bad season');
    END IF;
  END IF;
  IF jsonb_typeof(p->'ovr') = 'number' AND (p->>'ovr')::numeric BETWEEN 30 AND 99 THEN
    v_ovr := round((p->>'ovr')::numeric)::int;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM profiles WHERE id = uid) THEN
    RETURN jsonb_build_object('error', 'no profile');
  END IF;

  -- The first call writes the run; a concurrent or later one finds it here.
  INSERT INTO journey_runs (user_id, run_id, level, formation, route, broken, clubs, year_gap, backwards, ovr, rank,
                            wins, draws, losses, gf, ga, points, season_at)
  VALUES (uid, v_run, v_level, v_form, v_clean, v_broken, v_nclubs, v_gap, v_back, v_ovr, v_rank,
          v_w, v_d, v_l, v_gf, v_ga, CASE WHEN v_rank IS NULL THEN NULL ELSE 3 * v_w + v_d END,
          CASE WHEN v_rank IS NULL THEN NULL ELSE now() END)
  ON CONFLICT (user_id, run_id) DO NOTHING;
  SELECT * INTO v_row FROM journey_runs WHERE user_id = uid AND run_id = v_run;
  -- A later call may only fill in a season the row is still waiting for. The
  -- `rank IS NULL` is in the UPDATE itself, not only in the read above: two
  -- seasons sent at once both read NULL, and under Read Committed the second
  -- UPDATE waits for the first, re-checks, finds a rank and changes nothing.
  -- Re-reading afterwards gives both callers the rank that was actually kept.
  IF v_row.rank IS NULL AND v_rank IS NOT NULL THEN
    UPDATE journey_runs SET rank = v_rank, season_at = now(), ovr = COALESCE(ovr, v_ovr),
           wins = v_w, draws = v_d, losses = v_l, gf = v_gf, ga = v_ga, points = 3 * v_w + v_d
     WHERE id = v_row.id AND rank IS NULL;
    SELECT * INTO v_row FROM journey_runs WHERE id = v_row.id;
  END IF;

  -- awards from the stored row only, never from this request
  earned := array_append(earned, 'jx_finish');
  IF NOT v_row.broken          THEN earned := array_append(earned, 'jx_chain'); END IF;
  IF v_row.level = 'hard'      THEN earned := array_append(earned, 'jx_hard');  END IF;
  IF v_row.year_gap >= 20      THEN earned := array_append(earned, 'jx_time');  END IF;
  IF v_row.backwards >= 4      THEN earned := array_append(earned, 'jx_back');  END IF;
  IF v_row.rank = 1 AND v_row.level IN ('normal','hard') THEN earned := array_append(earned, 'jx_title'); END IF;

  WITH ins AS (
    INSERT INTO user_achievements (user_id, achievement_key)
    SELECT uid, k FROM unnest(earned) AS k
    ON CONFLICT DO NOTHING
    RETURNING achievement_key
  )
  SELECT COALESCE(array_agg(achievement_key), '{}') INTO fresh FROM ins;

  RETURN jsonb_build_object('achievements', to_jsonb(fresh));
END $$;

-- PUBLIC first: Postgres grants EXECUTE to PUBLIC by default, so revoking from
-- anon alone leaves anon its call (auth.uid() would still refuse it a write).
