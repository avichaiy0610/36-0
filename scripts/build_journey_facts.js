// A compact, reproducible subset of the historical final league tables.
// Run after updating js/data.js or js/league_tables.js.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const squads = new Function(read('js/data.js') + ';return SQUADS;')();
const tables = new Function(read('js/league_tables.js') + ';return LEAGUE_TABLES;')();
// 2009/10 and 2010/11 halved every club's points before the play-offs, so 26 points
// there is not a relegation season. A season is halved when most rows break 3W+D;
// a single mismatch elsewhere is a real deduction and stays as printed.
const halved = season => {
  const rows = (tables[season] || []).filter(r => r.w != null);
  return rows.length && rows.filter(r => r.pts !== 3 * r.w + r.d).length > rows.length / 2;
};
const facts = {};
squads.forEach(s => {
  const row = (tables[s.season] || []).find(r => r.teamId === s.teamId);
  if (row) facts[s.id] = halved(s.season) ? { pos: row.pos, pts: row.pts, half: 1 } : { pos: row.pos, pts: row.pts };
});
fs.writeFileSync(path.join(root, 'js/journey-facts.js'),
  '// Generated by scripts/build_journey_facts.js from final league tables.\nconst JOURNEY_FACTS = ' +
  JSON.stringify(facts) + ';\n');
console.log('Journey facts: ' + Object.keys(facts).length + ' squads');
