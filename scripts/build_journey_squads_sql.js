// Writes the squad list that submit_journey_run checks routes against into the
// generated block of supabase/migrations/20261013000002_journey_runs.sql.
// Run after js/data.js gains or loses squads — and, once that migration is live,
// ship the new ids in a NEW migration (INSERT ... ON CONFLICT DO NOTHING) instead:
// a route through a squad the server does not know earns nothing, though the game
// itself still plays. scripts/sim/journey_server_test.js fails while they differ.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const file = path.join(root, 'supabase/migrations/20261013000002_journey_runs.sql');
const squads = new Function(fs.readFileSync(path.join(root, 'js/data.js'), 'utf8') + ';return SQUADS;')();
const ids = squads.map(s => s.id).sort();
const BEGIN = '-- BEGIN journey_squads (generated by scripts/build_journey_squads_sql.js)';
const END = '-- END journey_squads';
const rows = [];
for (let i = 0; i < ids.length; i += 6) rows.push('  ' + ids.slice(i, i + 6).map(id => `('${id}')`).join(', '));
const block = `${BEGIN}\nINSERT INTO journey_squads (id) VALUES\n${rows.join(',\n')}\nON CONFLICT DO NOTHING;\n${END}`;
const sql = fs.readFileSync(file, 'utf8');
const a = sql.indexOf(BEGIN), b = sql.indexOf(END);
if (a < 0 || b < a) { console.error('generated block markers not found in ' + file); process.exit(1); }
fs.writeFileSync(file, sql.slice(0, a) + block + sql.slice(b + END.length));
console.log('journey_squads: ' + ids.length + ' squads');
